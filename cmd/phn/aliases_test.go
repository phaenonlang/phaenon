package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// aliasTree is a project whose namespace App\Orders declares type aliases
// in a file of their own, used by a file of another namespace, and which
// installed acme/lib, a library written in Phaenon that declares one too.
func aliasTree(t *testing.T) string {
	root := vendorTree(t)
	writeTree(t, root, map[string]string{
		"vendor/acme/lib/src/Bad.phn":   "namespace Acme\\Lib;\n\nfunction good(): int => 1;\n",
		"vendor/acme/lib/src/types.phn": "namespace Acme\\Lib;\n\ntype Boxes<T> = map<string, Box<T>>;\n",
		"vendor/acme/lib/src/Crate.phn": "namespace Acme\\Lib;\n\ntype Crate = list<Box<string>>;\n",
		"src/Orders/types.phn":          "namespace App\\Orders;\n\ntype Row = map<string, int|string>;\ntype Rows = list<Row>;\n",
		"src/Orders/Line.phn":           "namespace App\\Orders;\n\ntype Line = (string, int);\n",
		"src/Orders/Orders.phn":         "namespace App\\Orders;\n\nfinal class Orders\n{\n    all(): Rows => [];\n}\n",
		"src/Http/Show.phn": "namespace App\\Http;\n\nuse Acme\\Lib\\Boxes;\nuse App\\Orders\\Orders;\nuse App\\Orders\\Row;\n\n" +
			"final class Show\n{\n    first(Orders $orders): ?Row => $orders->all()[0] ?? null;\n\n    count(Boxes<int> $boxes): int => count($boxes);\n}\n",
		// The aliases a file named after them holds, the first names this
		// file meets: a class would be looked for there.
		"src/Http/Lines.phn": "namespace App\\Http;\n\nuse Acme\\Lib\\Crate;\nuse App\\Orders\\Line;\n\n" +
			"function quantity(Line $line, Crate $crate): int => $line[1] + count($crate);\n",
	})
	return root
}

// An alias is found by its declaration, never by a file name: the rest of
// the project in a run over given paths, and an installed Phaenon package,
// are read on demand, so a path's findings do not depend on how phn was
// called (design/generics.md §11.6).
func TestAliasesOfSourcesOutsideTheProgram(t *testing.T) {
	bin := phnBinary(t)
	root := aliasTree(t)
	for _, args := range [][]string{{"check"}, {"check", "src/Http"}, {"check", "src/Http/Show.phn"}, {"check", "src/Http/Lines.phn"}, {"check", "src/Orders/Orders.phn"}} {
		stdout, stderr, err := run(t, root, bin, args...)
		if err != nil || !strings.Contains(stdout, "0 errors, 0 warnings") {
			t.Errorf("phn %s (%v):\n%s%s", strings.Join(args, " "), err, stdout, stderr)
		}
	}
	// A name that is neither a class nor an alias is still unknown, in
	// either kind of run.
	writeTree(t, root, map[string]string{"src/Http/Lost.phn": "namespace App\\Http;\n\nuse App\\Orders\\Nope;\n\nfunction lost(Nope $n): void {}\n"})
	for _, args := range [][]string{{"check"}, {"check", "src/Http/Lost.phn"}} {
		_, stderr, err := run(t, root, bin, args...)
		if err == nil || !strings.Contains(stderr, `P2001: unknown class App\Orders\Nope`) {
			t.Errorf("phn %s (%v):\n%s", strings.Join(args, " "), err, stderr)
		}
	}
	if err := os.Remove(filepath.Join(root, "src/Http/Lost.phn")); err != nil {
		t.Fatal(err)
	}

	// The output of a path is what the project's build writes for it: the
	// aliases expanded, their imports left out.
	if stdout, stderr, err := run(t, root, bin, "build", "--out", "one", "src/Http/Show.phn"); err != nil {
		t.Fatalf("phn build of one path: %v\n%s%s", err, stdout, stderr)
	}
	if stdout, stderr, err := run(t, root, bin, "build"); err != nil {
		t.Fatalf("phn build: %v\n%s%s", err, stdout, stderr)
	}
	one, err := os.ReadFile(filepath.Join(root, "one/src/Http/Show.php"))
	if err != nil {
		t.Fatal(err)
	}
	all, err := os.ReadFile(filepath.Join(root, ".src/Http/Show.php"))
	if err != nil {
		t.Fatal(err)
	}
	body := func(out []byte) string { // the line map names the source by its path from the output
		i := strings.LastIndex(string(out), "\n// phaenon-map")
		return string(out[:i])
	}
	if body(one) != body(all) {
		t.Errorf("a path's output differs from the project's:\n%s\n---\n%s", one, all)
	}
	for _, want := range []string{
		"@return ?array<string, int|string>",
		"@param array<string, \\Acme\\Lib\\Box<int>> $boxes",
		"use App\\Orders\\Orders;",
	} {
		if !strings.Contains(string(all), want) {
			t.Errorf("the output lacks %q:\n%s", want, all)
		}
	}
	for _, not := range []string{"use App\\Orders\\Row;", "use Acme\\Lib\\Boxes;"} {
		if strings.Contains(string(all), not) {
			t.Errorf("the output keeps %q:\n%s", not, all)
		}
	}
	// A file that holds only `type` declarations has its output, with
	// nothing in it but the header and the namespace.
	types, err := os.ReadFile(filepath.Join(root, ".src/Orders/types.php"))
	if err != nil {
		t.Fatal(err)
	}
	const want = "<?php\n\n/* @generated by phaenon from types.phn */\n\ndeclare(strict_types=1);\n\nnamespace App\\Orders;\n\n// phaenon-map v1 ../../src/Orders/types.phn 1-6=1 7:1\n"
	if string(types) != want {
		t.Errorf("the output of a file of aliases:\n%s\nwant:\n%s", types, want)
	}
	if out, stderr, err := run(t, root, bin, "build", "--check"); err != nil {
		t.Errorf("phn build --check after a build (%v):\n%s%s", err, out, stderr)
	}
}

// phn migrate lifts the aliases PHP code has: a @phpstan-type becomes a
// `type` declaration before its class and a @phpstan-import-type a `use`,
// when their files are migrated together, and the migrated tree checks
// (design/collections.md §6.6).
func TestMigrateLiftsAliases(t *testing.T) {
	bin := phnBinary(t)
	root := formatTree(t)
	if err := os.Remove(filepath.Join(root, "src", "Bad.phn")); err != nil {
		t.Fatal(err)
	}
	writeTree(t, root, map[string]string{
		"vendor/composer/autoload_psr4.php": "<?php\n\n$vendorDir = dirname(__DIR__);\n$baseDir = dirname($vendorDir);\n\nreturn array(\n    'App\\\\' => array($baseDir . '/.src'),\n);\n",
		"src/Orders/Orders.php": "<?php\n\ndeclare(strict_types=1);\n\nnamespace App\\Orders;\n\n/**\n * @phpstan-type Row array{id: int, name?: string}\n * @phpstan-type Page array{items: list<Row>, total: int}\n */\nfinal class Orders\n{\n" +
			"    /** @var list<Row> */\n    private array $rows = [];\n\n    /**\n     * @return Page\n     */\n    public function page(): array\n    {\n        return ['items' => $this->rows, 'total' => count($this->rows)];\n    }\n}\n",
		"src/Http/Show.php": "<?php\n\ndeclare(strict_types=1);\n\nnamespace App\\Http;\n\nuse App\\Orders\\Orders;\n\n/**\n * @phpstan-import-type Row from Orders\n * @phpstan-import-type Page from Orders as Paged\n */\nfinal class Show\n{\n" +
			"    /**\n     * @param Paged $page\n     * @return Row|null\n     */\n    public function first(array $page): ?array\n    {\n        return $page['items'][0] ?? null;\n    }\n}\n",
	})
	stdout, stderr, err := run(t, root, bin, "migrate", "src")
	if err != nil || !strings.Contains(stdout, "2 files migrated, 0 skipped, 0 .phn files updated, 0 docblock tags kept") {
		t.Fatalf("phn migrate (%v):\n%s%s", err, stdout, stderr)
	}
	orders, _ := os.ReadFile(filepath.Join(root, "src/Orders/Orders.phn"))
	show, _ := os.ReadFile(filepath.Join(root, "src/Http/Show.phn"))
	for _, want := range []string{"type Row = array{id: int, name?: string};\ntype Page = array{items: list<Row>, total: int};\n\nfinal class Orders", "private list<Row> $rows = [];", "page(): Page =>"} {
		if !strings.Contains(string(orders), want) {
			t.Errorf("Orders.phn lacks %q:\n%s", want, orders)
		}
	}
	for _, want := range []string{"use App\\Orders\\Orders;\nuse App\\Orders\\Row;\nuse App\\Orders\\Page as Paged;\n", "first(Paged $page): ?Row =>"} {
		if !strings.Contains(string(show), want) {
			t.Errorf("Show.phn lacks %q:\n%s", want, show)
		}
	}
	if strings.Contains(string(orders)+string(show), "@phpstan-") {
		t.Errorf("a tag was left:\n%s\n%s", orders, show)
	}
	for _, args := range [][]string{{"check"}, {"check", "src/Http"}, {"fmt", "--check"}} {
		if stdout, stderr, err := run(t, root, bin, args...); err != nil {
			t.Errorf("phn %s on the migrated tree (%v):\n%s%s", strings.Join(args, " "), err, stdout, stderr)
		}
	}
}
