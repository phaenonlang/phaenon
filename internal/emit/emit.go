// Package emit turns Phaenon source into PHP source.
//
// The emitter is patch-based: the output is the input text with a list of
// span edits applied. Everything the emitter has no reason to touch —
// comments, formatting, code that is already plain PHP — passes through byte
// for byte, and every edit replaces a span with text that has the same
// number of line breaks. So line N of the generated .php is line N of the
// .phn, and stack traces, __LINE__, Xdebug, PHPUnit coverage and PHPStan all
// point at the Phaenon source without source maps.
//
// The price is paid on line 1: the PHP open tag, the @generated marker and
// declare(strict_types=1) share it with whatever the .phn has there.
//
// Phaenon constructs that need rewriting (generics erasure, is/as, …) become
// further edits in later milestones; the printer renders synthesised
// fragments, which are then spliced in by this package.
package emit

import (
	"bytes"
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	"github.com/phaenonlang/phaenon/internal/ast"
	"github.com/phaenonlang/phaenon/internal/lexer"
	"github.com/phaenonlang/phaenon/internal/parser"
	"github.com/phaenonlang/phaenon/internal/program"
)

// Marker is the comment that identifies generated output; it is always on
// line 1 of an emitted file. Tools (phn migrate, phn build --clean) use it
// to tell generated .php files from hand-written ones.
const Marker = "@generated by phaenon"

// Options control emission.
type Options struct {
	// SourceName is the .phn path recorded in the marker (base name only).
	SourceName string
	// StrictTypes injects declare(strict_types=1) unless the file declares
	// strict_types itself. Phaenon is strict by default; the conformance
	// suite turns this off to compare against non-strict PHP tests.
	StrictTypes bool
	// Program and File carry the type information generics need (the
	// checked program and this file's entry in it). A file that uses
	// Phaenon type syntax cannot be compiled without them.
	Program *program.Program
	File    *program.File
}

// Error is an emission error at a source position.
type Error struct {
	File string
	Line int
	Msg  string
}

func (e *Error) Error() string {
	if e.File == "" {
		return fmt.Sprintf("line %d: %s", e.Line, e.Msg)
	}
	return fmt.Sprintf("%s:%d: %s", e.File, e.Line, e.Msg)
}

// File compiles one .phn source to PHP.
func File(src []byte, opts Options) ([]byte, error) {
	if opts.File != nil && opts.File.AST != nil {
		// The checker's tree: its records (method targets, …) key on nodes.
		return Tree(src, opts.File.AST, opts)
	}
	f, err := parser.Parse(src, lexer.ModePhaenon)
	if err != nil {
		if pe, ok := err.(*parser.Error); ok {
			return nil, &Error{File: opts.SourceName, Line: pe.Line, Msg: pe.Msg}
		}
		return nil, err
	}
	return Tree(src, f, opts)
}

// Tree compiles an already parsed file. src must be the text f was parsed from.
func Tree(src []byte, f *ast.File, opts Options) ([]byte, error) {
	e := &emitter{src: src, opts: opts}
	if err := e.lowerGenerics(f); err != nil {
		return nil, err
	}
	e.lowerFunctions(f)
	e.prologue(f)
	return e.apply(), nil
}

// IsGenerated reports whether src carries the generated marker on line 1.
func IsGenerated(src []byte) bool {
	line := src
	if i := bytes.IndexByte(src, '\n'); i >= 0 {
		line = src[:i]
	}
	return bytes.Contains(line, []byte(Marker))
}

// ------------------------------------------------------------------ edits

// edit replaces src[Start:End) with Text. Text must contain as many line
// breaks as the span it replaces.
type edit struct {
	ast.Span
	Text string
}

type emitter struct {
	src   []byte
	opts  Options
	edits []edit
	// imports are the classes the compiler introduced, by fully qualified
	// name, with the short name each is called by in this file ("" when the
	// name is taken and the FQCN is used): roadmap D11.
	imports map[string]string
	// ownImports are the compiler-introduced classes the file already
	// imports itself: used by their alias, not added to the use list.
	ownImports map[string]bool
}

func (e *emitter) replace(s ast.Span, text string) {
	if got, want := strings.Count(text, "\n"), bytes.Count(e.src[s.Start:s.End], []byte("\n")); got != want {
		panic(fmt.Sprintf("emit: edit at %d changes the line count (%d → %d): %q", s.Start, want, got, text))
	}
	e.edits = append(e.edits, edit{s, text})
}

func (e *emitter) insert(at int, text string) {
	e.replace(ast.Span{Start: at, End: at}, text)
}

// replaceLines is replace for the one kind of edit that may add lines: a
// docblock, which PHPStan reads one tag per line. Lines after it shift.
func (e *emitter) replaceLines(s ast.Span, text string) {
	e.edits = append(e.edits, edit{s, text})
}

func (e *emitter) insertLines(at int, text string) {
	e.replaceLines(ast.Span{Start: at, End: at}, text)
}

// apply splices the edits into the source. Edits must not overlap; insertions
// at the same offset keep their order of registration.
func (e *emitter) apply() []byte {
	sort.SliceStable(e.edits, func(i, j int) bool { return e.edits[i].Start < e.edits[j].Start })
	var out bytes.Buffer
	out.Grow(len(e.src) + 128)
	pos := 0
	for _, ed := range e.edits {
		if ed.Start < pos {
			panic("emit: overlapping edits")
		}
		out.Write(e.src[pos:ed.Start])
		out.WriteString(ed.Text)
		pos = ed.End
	}
	out.Write(e.src[pos:])
	return out.Bytes()
}

func (e *emitter) lineOf(offset int) int {
	return 1 + bytes.Count(e.src[:offset], []byte("\n"))
}

func (e *emitter) errorf(n ast.Node, format string, args ...any) error {
	return &Error{File: e.opts.SourceName, Line: e.lineOf(n.Span().Start), Msg: fmt.Sprintf(format, args...)}
}

// ------------------------------------------------------------------ passes

// prologue puts the open tag, the marker and (unless the file has its own)
// declare(strict_types=1) at the start of line 1.
func (e *emitter) prologue(f *ast.File) {
	var sb strings.Builder
	sb.WriteString("<?php /* ")
	sb.WriteString(Marker)
	if e.opts.SourceName != "" {
		sb.WriteString(" from ")
		sb.WriteString(filepath.Base(e.opts.SourceName))
	}
	sb.WriteString(" */ ")
	if e.opts.StrictTypes && !declaresStrictTypes(f) {
		sb.WriteString("declare(strict_types=1); ")
	}
	// The imports the lowering asked for go after the namespace statement,
	// on its line; a file without one gets them on this line.
	if uses := e.useStatements(); uses != "" {
		if end := namespaceEnd(f); end >= 0 {
			e.insert(end, " "+uses)
		} else {
			sb.WriteString(uses + " ")
		}
	}
	e.insert(0, sb.String())
}

// useStatements renders the compiler's imports, sorted.
func (e *emitter) useStatements() string {
	var names []string
	for fqcn, short := range e.imports {
		if short != "" && !e.ownImports[fqcn] {
			names = append(names, fqcn)
		}
	}
	sort.Strings(names)
	var sb strings.Builder
	for i, n := range names {
		if i > 0 {
			sb.WriteString(" ")
		}
		sb.WriteString("use " + n + ";")
	}
	return sb.String()
}

// namespaceEnd is the offset after the file's single unbraced namespace
// statement, -1 when the file has none, -2 when imports cannot be placed
// (braced or several namespaces: importShort then falls back to the FQCN).
func namespaceEnd(f *ast.File) int {
	end := -1
	for _, s := range f.Stmts {
		if ns, ok := s.(*ast.Namespace); ok {
			if ns.Braced || end != -1 {
				return -2
			}
			end = ns.S.End
		}
	}
	return end
}

// importShort returns the name a compiler-introduced class is called by in
// this file: its short name, imported with `use`, unless that name is taken
// by a user import or a class of the namespace, or imports cannot be placed
// — then the fully qualified name (roadmap D11).
func (e *emitter) importShort(fqcn string, res *program.Resolver) string {
	if e.imports == nil {
		e.imports = map[string]string{}
		e.ownImports = map[string]bool{}
	}
	if short, seen := e.imports[fqcn]; seen {
		if short == "" {
			return "\\" + fqcn
		}
		return short
	}
	short := fqcn[strings.LastIndex(fqcn, "\\")+1:]
	taken := namespaceEnd(e.opts.File.AST) == -2
	for alias, target := range res.Scope().Imports() {
		if strings.EqualFold(target, fqcn) {
			// The file imports the class itself: use its name, add nothing.
			if written := importAlias(e.opts.File.AST, fqcn); written != "" {
				alias = written
			}
			e.imports[fqcn] = alias
			e.ownImports[fqcn] = true
			return alias
		}
		if strings.EqualFold(alias, short) {
			taken = true
		}
	}
	for other, s := range e.imports {
		if s == short && other != fqcn {
			taken = true
		}
	}
	if e.opts.Program.Class(res.Scope().Prefix()+short) != nil {
		taken = true
	}
	if taken {
		e.imports[fqcn] = ""
		return "\\" + fqcn
	}
	e.imports[fqcn] = short
	return short
}

// importAlias is the name a file's own use statement gives fqcn, as
// written (the scope keeps it lower-cased), or "" when the file does not
// import it.
func importAlias(f *ast.File, fqcn string) string {
	alias := ""
	ast.Inspect(f, func(n ast.Node) bool {
		u, ok := n.(*ast.Use)
		if !ok {
			return alias == ""
		}
		for _, item := range u.Items {
			var parts []string
			if u.Prefix != nil {
				parts = append(parts, u.Prefix.Parts...)
			}
			parts = append(parts, item.Name.Parts...)
			if !strings.EqualFold(strings.Join(parts, "\\"), fqcn) {
				continue
			}
			if item.Alias != nil {
				alias = item.Alias.Name
			} else {
				alias = parts[len(parts)-1]
			}
		}
		return false
	})
	return alias
}

// declaresStrictTypes reports whether the first statement is a declare with
// a strict_types directive (PHP requires it to be first, so that is the only
// place to look).
func declaresStrictTypes(f *ast.File) bool {
	if len(f.Stmts) == 0 {
		return false
	}
	d, ok := f.Stmts[0].(*ast.Declare)
	if !ok {
		return false
	}
	for _, dir := range d.Directives {
		if strings.EqualFold(dir.Name.Name, "strict_types") {
			return true
		}
	}
	return false
}
