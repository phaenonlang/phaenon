const clean = "namespace App;\n\nfunction greet(string $name): string => \"Hello, {$name}\";\n"

// broken returns a string where its type promises an int: P2202 on line 3.
const broken = "namespace App;\n\nfunction broken(): int => 'not an int';\n"

func codes(fs []Finding) []string {
	var out []string
	for _, f := range fs {
		out = append(out, f.Code)
	}
	return out
}

func TestCleanFile(t *testing.T) {
	res := Compile(Request{Files: map[string]string{"main.phn": clean}, Main: "main.phn"})
	if !res.OK || len(res.Findings) != 0 {
		t.Fatalf("ok %v, findings %v", res.OK, res.Findings)
	}
	for _, want := range []string{"<?php\n", "@generated by phaenon", "declare(strict_types=1);", "function greet(string $name): string\n{"} {
		if !strings.Contains(res.PHP, want) {
			t.Errorf("output lacks %q:\n%s", want, res.PHP)
		}
	}
	// The line map names the source beside the output, as phn build's does.
	if !strings.Contains(res.PHP, "// phaenon-map v1 main.phn ") {
		t.Errorf("the line map does not name main.phn:\n%s", res.PHP)
	}
}

// D10: a file with an error gets no output unless asked, and the result is
// not OK either way.
func TestErrorWithheld(t *testing.T) {
	files := map[string]string{"main.phn": broken}
	res := Compile(Request{Files: files, Main: "main.phn"})
	if res.OK || res.PHP != "" {
		t.Errorf("without emitOnError: ok %v, php %q", res.OK, res.PHP)
	}
	if len(res.Findings) != 1 {
		t.Fatalf("findings %v", res.Findings)
	}
	f := res.Findings[0]
	if f.Code != "P2202" || f.File != "main.phn" || f.Line != 3 || f.Severity != "error" || f.Column == 0 || f.Message == "" {
		t.Errorf("finding %+v", f)
	}
	res = Compile(Request{Files: files, Main: "main.phn", EmitOnError: true})
	if res.OK || !strings.Contains(res.PHP, "function broken(): int") {
		t.Errorf("with emitOnError: ok %v, php %q", res.OK, res.PHP)
	}
	if strings.Join(codes(res.Findings), ",") != "P2202" {
		t.Errorf("with emitOnError, findings %v", res.Findings)
	}
}

