// A class from outside the file is unknown, as in phn check; a support
// file, Phaenon or PHP, declares it. Support files are checked too.
func TestSupportFiles(t *testing.T) {
	main := "namespace App;\n\nuse Acme\\Clock;\n\nfunction run(Clock $c): string => (new Greeter())->hello((string) $c->now());\n"
	res := Compile(Request{Files: map[string]string{"main.phn": main}, Main: "main.phn"})
	unknown := map[string]bool{}
	for _, f := range res.Findings {
		if f.Code == "P2001" {
			unknown[f.Message] = true
		}
	}
	if res.OK || !unknown[`unknown class Acme\Clock`] || !unknown[`unknown class App\Greeter`] {
		t.Errorf("alone: ok %v, findings %v", res.OK, res.Findings)
	}
	files := map[string]string{
		"main.phn":         main,
		"lib/Greeter.phn":  "namespace App;\n\nfinal class Greeter\n{\n    hello(string $n): string => \"Hello, {$n}\";\n}\n",
		"vendor/Clock.php": "<?php\n\nnamespace Acme;\n\nfinal class Clock\n{\n    public function now(): int\n    {\n        return 1;\n    }\n}\n",
		"notes.txt":        "not a source",
	}
	res = Compile(Request{Files: files, Main: "main.phn"})
	if !res.OK || len(res.Findings) != 0 || !strings.Contains(res.PHP, "function run(Clock $c): string") {
		t.Errorf("with the support files: ok %v, findings %v\n%s", res.OK, res.Findings, res.PHP)
	}
	// Only the main file is compiled.
	if strings.Contains(res.PHP, "class Greeter") {
		t.Errorf("a support file was compiled into the output:\n%s", res.PHP)
	}
	files["lib/Greeter.phn"] = "namespace App;\n\nfinal class Greeter\n{\n    hello(string $n): string => \"Hello, {$n}\";\n\n    count(): int => 'one';\n}\n"
	res = Compile(Request{Files: files, Main: "main.phn"})
	if res.OK || len(res.Findings) == 0 || res.Findings[0].File != "lib/Greeter.phn" {
		t.Errorf("an error in a support file: ok %v, findings %+v", res.OK, res.Findings)
	}
	// phn build withholds the outputs of the files with errors, not of the
	// files that use them.
	if res.PHP == "" {
		t.Error("the main file's output was withheld for a support file's error")
	}
}

// The output is the target's: partial application is lowered for 8.5 and
// written as such for 8.6; a target phn does not compile for is P4009 and
// compiles nothing.
func TestTargets(t *testing.T) {
	src := "function pair(string $a, string $b): string => \"[$a|$b]\";\n\n$f = pair('x', ?);\n"
	for _, c := range []struct{ target, want string }{
		{"", "fn(string $b) => pair('x', $b)"},
		{"8.5", "fn(string $b) => pair('x', $b)"},
		{"8.6", "pair('x', ?)"},
	} {
		res := Compile(Request{Files: map[string]string{"main.phn": src}, Main: "main.phn", Target: c.target})
		if !res.OK || !strings.Contains(res.PHP, c.want) {
			t.Errorf("target %q: ok %v, findings %v, output lacks %q:\n%s", c.target, res.OK, res.Findings, c.want, res.PHP)
		}
	}
	for _, target := range []string{"8.4", "9.0", "eight"} {
		res := Compile(Request{Files: map[string]string{"main.phn": clean}, Main: "main.phn", Target: target, EmitOnError: true})
		if res.OK || res.PHP != "" || strings.Join(codes(res.Findings), ",") != "P4009" {
			t.Errorf("target %q: ok %v, php %q, findings %v", target, res.OK, res.PHP, res.Findings)
		}
	}
}

// A panic in any stage is one P0000 finding after the findings already
// made, with no output; the next call compiles as if nothing happened.
func TestPanic(t *testing.T) {
	defer func() { stageHook = nil }()
	for _, stage := range []string{"parsing", "checking", "compiling"} {
		stageHook = func(s string) {
			if s == stage {
				panic("made to fail")
			}
		}
		res := Compile(Request{Files: map[string]string{"main.phn": broken}, Main: "main.phn", EmitOnError: true})
		last := res.Findings[len(res.Findings)-1]
		if res.OK || res.PHP != "" || last.Code != Internal || last.Severity != "error" ||
			last.Message != "internal error while "+stage+": made to fail" {
			t.Errorf("panic while %s: ok %v, php %q, findings %+v", stage, res.OK, res.PHP, res.Findings)
		}
	}
	stageHook = nil
	if res := Compile(Request{Files: map[string]string{"main.phn": clean}, Main: "main.phn"}); !res.OK || res.PHP == "" {
		t.Errorf("after the panics: ok %v, findings %v", res.OK, res.Findings)
	}
}

func TestMisuse(t *testing.T) {
	for _, req := range []Request{
		{Files: map[string]string{"main.phn": clean}},
		{Files: map[string]string{"main.php": clean}, Main: "main.php"},
		{Files: map[string]string{"other.phn": clean}, Main: "main.phn"},
		{Files: map[string]string{"main.phn": clean, "<stub>/Zend/zend_builtin_functions.stub.php": "<?php\n"}, Main: "main.phn"},
	} {
		res := Compile(req)
		if res.OK || res.PHP != "" || strings.Join(codes(res.Findings), ",") != Internal {
			t.Errorf("%v: ok %v, findings %v", req, res.OK, res.Findings)
		}
	}
}

// What the page passes: the defaults (main.phn, phn's floor, no further
// files, emitOnError true) and each option.
func TestCompilePage(t *testing.T) {
	for _, opts := range []string{"", "null", "{}"} {
		res := CompilePage(broken, []byte(opts))
		if res.OK || len(res.Findings) != 1 || res.Findings[0].File != DefaultFilename || res.PHP == "" {
			t.Errorf("options %q: ok %v, findings %v, php %q", opts, res.OK, res.Findings, res.PHP)
		}
	}
	res := CompilePage(broken, []byte(`{"filename": "src/Broken.phn", "target": "8.6", "emitOnError": false}`))
	if res.OK || res.PHP != "" || res.Findings[0].File != "src/Broken.phn" {
		t.Errorf("options: ok %v, findings %v, php %q", res.OK, res.Findings, res.PHP)
	}
	res = CompilePage("namespace App;\n\nfunction run(): string => (new Greeter())->hello('x');\n",
		[]byte(`{"files": {"Greeter.phn": "namespace App;\n\nfinal class Greeter\n{\n    hello(string $n): string => $n;\n}\n"}}`))
	if !res.OK || res.PHP == "" {
		t.Errorf("files: ok %v, findings %v", res.OK, res.Findings)
	}
	for _, opts := range []string{
		`{"check": true}`,
		`{"target": 8.6}`,
		`"8.6"`,
		`{"files": {"main.phn": "namespace App;\n"}}`,
		`{"files": {"a.phn": 1}}`,
	} {
		res := CompilePage(clean, []byte(opts))
		if res.OK || res.PHP != "" || strings.Join(codes(res.Findings), ",") != Internal {
			t.Errorf("options %s: ok %v, findings %v", opts, res.OK, res.Findings)
		}
	}
}

// The JSON the page parses: the field names of the contract, findings an
// array even when empty, the end left out when unknown.
func TestJSON(t *testing.T) {
	var empty map[string]any
	if err := json.Unmarshal(CompilePage(clean, nil).JSON(), &empty); err != nil {
		t.Fatal(err)
	}
	if fs, ok := empty["findings"].([]any); !ok || len(fs) != 0 || empty["ok"] != true || empty["php"] == "" {
		t.Errorf("clean: %v", empty)
	}
	got := string(Result{Findings: []Finding{
		{File: "main.phn", Line: 3, Column: 22, EndLine: 3, EndColumn: 34, Code: "P2202", Severity: "error", Message: "m"},
		{File: "main.phn", Line: 1, Column: 1, Code: "P0000", Severity: "error", Message: "m"},
	}}.JSON())
	want := `{"ok":false,"php":"","findings":[` +
		`{"file":"main.phn","line":3,"column":22,"endLine":3,"endColumn":34,"code":"P2202","severity":"error","message":"m"},` +
		`{"file":"main.phn","line":1,"column":1,"code":"P0000","severity":"error","message":"m"}]}`
	if got != want {
		t.Errorf("JSON\n got %s\nwant %s", got, want)
	}
}

// Every emitter golden compiles in the playground to the golden itself,
// for each of its targets: the page writes what phn build writes.
func TestEmitGoldens(t *testing.T) {
	paths, _ := filepath.Glob("../emit/testdata/*.phn")
	if len(paths) == 0 {
		t.Skip("no emitter goldens")
	}
	for _, path := range paths {
		src, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		name := filepath.Base(path)
		for i, target := range goldenTargets(string(src)) {
			want := strings.TrimSuffix(path, ".phn") + ".php"
			if i > 0 {
				want = strings.TrimSuffix(path, ".phn") + "." + target + ".php"
			}
			golden, err := os.ReadFile(want)
			if err != nil {
				t.Fatal(err)
			}
			res := Compile(Request{Files: map[string]string{name: string(src)}, Main: name, Target: target})
			if !res.OK || res.PHP != string(golden) {
				t.Errorf("%s for %s: ok %v, findings %v; the output differs from %s", name, target, res.OK, res.Findings, filepath.Base(want))
			}
		}
	}
}

// goldenTargets reads an emitter golden's `// targets: 8.5, 8.6` line; the
// floor without one.
func goldenTargets(src string) []string {
	first, _, _ := strings.Cut(src, "\n")
	list, ok := strings.CutPrefix(first, "// targets:")
	if !ok {
		return []string{phpversion.Floor.String()}
	}
	var out []string
	for _, t := range strings.Split(list, ",") {
		out = append(out, strings.TrimSpace(t))
	}
	return out
}
