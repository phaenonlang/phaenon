package trace

import (
	"os"
	"path/filepath"
	"testing"
)

func TestRewrite(t *testing.T) {
	dir := t.TempDir()
	compiled := "<?php\n\n/* @generated by phaenon from Foo.phn */\n\n" +
		"declare(strict_types=1);\n\nnamespace App;\n\nfinal class Foo\n{\n" +
		"// phaenon-map v1 ../src/Foo.phn 1-6=1 7:1 10-10=3 11:4\n"
	mustWrite(t, filepath.Join(dir, ".src", "Foo.php"), compiled)
	mustWrite(t, filepath.Join(dir, ".src", "Plain.php"), "<?php\necho 1;\n")
	foo := filepath.Join(dir, ".src", "Foo.php")
	src := filepath.Join(dir, "src", "Foo.phn")

	cases := []struct {
		name, in, want string
		roots          []Root
	}{
		{"path:line", foo + ":12", src + ":5", nil},
		{"getTraceAsString", "#0 " + foo + "(9): App\\Foo->bar()", "#0 " + src + "(3): App\\Foo->bar()", nil},
		{"a warning", "Warning: x in " + foo + " on line 7", "Warning: x in " + src + " on line 1", nil},
		{"PHPStan raw", foo + ":11:Method App\\Foo::bar() has no return type.", src + ":4:Method App\\Foo::bar() has no return type.", nil},
		{"the header holds to line 1", foo + ":3", src + ":1", nil},
		{"several on a line", foo + ":7 and " + foo + ":12", src + ":1 and " + src + ":5", nil},
		{"a file without a map", filepath.Join(dir, ".src", "Plain.php") + ":2", filepath.Join(dir, ".src", "Plain.php") + ":2", nil},
		{"a file that does not exist", "/nowhere/Foo.php:3", "/nowhere/Foo.php:3", nil},
		{"no position", "nothing to see in Foo.php here", "nothing to see in Foo.php here", nil},
		{"a production root", "/app/.src/Foo.php:12", src + ":5", []Root{{Prefix: "/app", Local: dir}}},
		{"the longest root wins", "/app/.src/Foo.php:12", src + ":5", []Root{{Prefix: "/", Local: "/nowhere"}, {Prefix: "/app", Local: dir}}},
		{"a root matches whole segments", "/application/.src/Foo.php:12", "/application/.src/Foo.php:12", []Root{{Prefix: "/app", Local: dir}}},
	}
	for _, c := range cases {
		tr := New(c.roots)
		if got := tr.Rewrite(c.in); got != c.want {
			t.Errorf("%s:\n got %q\nwant %q", c.name, got, c.want)
		}
	}
}

func TestReadsEachFileOnce(t *testing.T) {
	reads := 0
	tr := New(nil)
	tr.ReadFile = func(string) ([]byte, error) {
		reads++
		return []byte("<?php\necho 1;\n// phaenon-map v1 Foo.phn 1-1=1 2:1\n"), nil
	}
	for i := 0; i < 3; i++ {
		if got := tr.Rewrite("Foo.php:2"); got != "Foo.phn:1" {
			t.Fatalf("got %q", got)
		}
	}
	if reads != 1 {
		t.Errorf("read the file %d times", reads)
	}
}

func TestParseRoot(t *testing.T) {
	if r, ok := ParseRoot("/app/=."); !ok || r.Prefix != "/app" || r.Local != "." {
		t.Errorf("got %+v, %v", r, ok)
	}
	for _, bad := range []string{"/app", "=.", "/app="} {
		if _, ok := ParseRoot(bad); ok {
			t.Errorf("%q accepted", bad)
		}
	}
}

func mustWrite(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}
