func TestCommandRoundTrip(t *testing.T) {
	c := Command{Name: "error", Props: []Prop{{"file", "a,b:c%.phn"}, {"line", "3"}, {"title", "P2103"}}, Message: "50% done,\nnext: line"}
	line := c.String()
	if want := "::error file=a%2Cb%3Ac%25.phn,line=3,title=P2103::50%25 done,%0Anext: line"; line != want {
		t.Errorf("got  %s\nwant %s", line, want)
	}
	back, ok := ParseCommand(line)
	if !ok || back.Name != c.Name || back.Message != c.Message || len(back.Props) != 3 || back.Props[0] != c.Props[0] {
		t.Errorf("parsed back as %+v", back)
	}
}

func TestParseCommandRefuses(t *testing.T) {
	for _, line := range []string{"::debug::x", "::group::Build", "error file=a::x", "::error file=a", "::error file::x", " ::error::x"} {
		if c, ok := ParseCommand(line); ok {
			t.Errorf("%q parsed as %+v", line, c)
		}
	}
	if c, ok := ParseCommand("::error::no file"); !ok || len(c.Props) != 0 || c.Message != "no file" {
		t.Errorf("::error::no file parsed as %+v, %v", c, ok)
	}
}

// PHPStan's --error-format=github: the file and the lines become the
// source's, the columns go, the message's positions are rewritten too, and
// a command on a file without a map is left as it is.
func TestRewriteCommands(t *testing.T) {
	// The project is app/ in a repository. An annotation names the source by
	// its path in the repository; a position in free text keeps the path as
	// it was written.
	repo := t.TempDir()
	mustWrite(t, filepath.Join(repo, ".git", "HEAD"), "ref: refs/heads/main\n")
	dir := filepath.Join(repo, "app")
	compiled := "<?php\n\n/* @generated by phaenon from Foo.phn */\n\n" +
		"declare(strict_types=1);\n\nnamespace App;\n\nfinal class Foo\n{\n" +
		"// phaenon-map v1 ../src/Foo.phn 1-6=1 7:1 10-10=3 11:4\n"
	mustWrite(t, filepath.Join(dir, ".src", "Foo.php"), compiled)
	mustWrite(t, filepath.Join(dir, "a,b", ".src", "Foo.php"), compiled)
	t.Chdir(dir)
	foo := filepath.Join(dir, ".src", "Foo.php")
	src := filepath.Join(dir, "src", "Foo.phn")
	cases := []struct{ name, in, want string }{
		{"PHPStan", "::error file=.src/Foo.php,line=12,col=0::Method has no return type.\n",
			"::error file=app/src/Foo.phn,line=5::Method has no return type.\n"},
		{"an absolute path", "::error file=" + foo + ",line=12,col=0::m\n",
			"::error file=app/src/Foo.phn,line=5::m\n"},
		{"every property", "::warning file=" + foo + ",line=7,endLine=12,col=3,endColumn=9,title=x::m\r\n",
			"::warning file=app/src/Foo.phn,line=1,endLine=5,title=x::m\r\n"},
		{"the message", "::notice file=" + foo + ",line=12::see " + foo + ":7",
			"::notice file=app/src/Foo.phn,line=5::see " + src + ":1"},
		{"an escaped path", "::error file=a%2Cb/.src/Foo.php,line=12::m",
			"::error file=app/a%2Cb/src/Foo.phn,line=5::m"},
		{"no map", "::error file=/nowhere/Foo.php,line=12,col=0::50% of " + foo + ":12",
			"::error file=/nowhere/Foo.php,line=12,col=0::50% of " + src + ":5"},
		{"no file", "::error ::Ignored error pattern was not matched", "::error ::Ignored error pattern was not matched"},
		{"lines around it", "first " + foo + ":12\n::error file=" + foo + ",line=12::m\nlast",
			"first " + src + ":5\n::error file=app/src/Foo.phn,line=5::m\nlast"},
	}
	for _, c := range cases {
		if got := New(nil).Rewrite(c.in); got != c.want {
			t.Errorf("%s:\n got %q\nwant %q", c.name, got, c.want)
		}
	}
}

// An annotation's path starts at the repository that holds the file; without
// one, at GITHUB_WORKSPACE, then at the working directory.
func TestAnnotationPath(t *testing.T) {
	root := t.TempDir()
	mustWrite(t, filepath.Join(root, "repo", ".git", "HEAD"), "ref: refs/heads/main\n")
	mustWrite(t, filepath.Join(root, "worktree", ".git"), "gitdir: ../repo/.git/worktrees/w\n")
	plain := filepath.Join(root, "plain")
	mustWrite(t, filepath.Join(plain, "app", "src", "Foo.phn"), "")
	t.Chdir(filepath.Join(plain, "app"))
	elsewhere := filepath.Join(root, "elsewhere", "Foo.phn")
	t.Setenv("GITHUB_WORKSPACE", "")
	for path, want := range map[string]string{
		filepath.Join(root, "repo", "app", "src", "Foo.phn"): "app/src/Foo.phn",
		filepath.Join(root, "worktree", "src", "Foo.phn"):    "src/Foo.phn",
		filepath.Join(plain, "app", "src", "Foo.phn"):        "src/Foo.phn",
		"src/Foo.phn": "src/Foo.phn",
		elsewhere:     filepath.ToSlash(elsewhere),
	} {
		if got := AnnotationPath(path); got != want {
			t.Errorf("AnnotationPath(%s) = %s, want %s", path, got, want)
		}
	}
	t.Setenv("GITHUB_WORKSPACE", plain)
	if got := AnnotationPath("src/Foo.phn"); got != "app/src/Foo.phn" {
		t.Errorf("under GITHUB_WORKSPACE: %s, want app/src/Foo.phn", got)
	}
}
