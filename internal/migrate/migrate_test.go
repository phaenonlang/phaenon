func TestFile(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{"psr-12 header", "<?php\n\ndeclare(strict_types=1);\n\nnamespace App;\n\nclass A {}\n", "namespace App;\n\nclass A {}\n"},
		{"one-line header", "<?php declare(strict_types=1);\nnamespace App;\n", "namespace App;\n"},
		{"no declare", "<?php\n\necho 1;\n", "echo 1;\n"},
		{"comment between tag and declare", "<?php\n// licence\ndeclare(strict_types=1);\n\necho 1;\n", "// licence\n\n\necho 1;\n"},
		{"other declare stays", "<?php\ndeclare(strict_types=0);\necho 1;\n", "declare(strict_types=0);\necho 1;\n"},
		{"declare with ticks stays", "<?php\ndeclare(strict_types=1, ticks=1);\n", "declare(strict_types=1, ticks=1);\n"},
		{"not first statement stays", "<?php\necho 1;\ndeclare(strict_types=1);\n", "echo 1;\ndeclare(strict_types=1);\n"},
		{"tag only", "<?php\n", ""},
		{"trailing close tag dropped", "<?php\necho 1;\n?>\n", "echo 1;\n"},
		{"trailing close tag without newline", "<?php\necho 1;\n?>", "echo 1;\n"},
		{"close tag as terminator", "<?php\necho 1 ?>\n", "echo 1; \n"},
		{"close tag after block", "<?php\nif (1) { echo 1; } ?>", "if (1) { echo 1; } "},
		{"close tag after comment", "<?php\necho 1; // x ?>\n", "echo 1; // x \n"},
		{"anonymous class before close tag", "<?php\n$c = new class {\n};\n?>\n", "$c = new class {\n};\n"},
		{"anonymous class relies on close tag", "<?php\n$c = new class {\n}\n?>\n", "$c = new class {\n};\n"},
		{"alt syntax relies on close tag", "<?php\nif (1): echo 1; endif ?>", "if (1): echo 1; endif; "},
		{"label before close tag", "<?php\nx: ?>", "x: "},
		{"close tag on its own line", "<?php\necho 1;\n\n?>\n", "echo 1;\n"},
		{"only tags", "<?php ?>", ""},
		{"crlf", "<?php\r\n\r\necho 1;\r\n", "echo 1;\r\n"},
	}
	for _, c := range cases {
		got, err := File([]byte(c.in), Options{})
		if err != nil {
			t.Errorf("%s: %v", c.name, err)
			continue
		}
		if string(got) != c.want {
			t.Errorf("%s:\n got %q\nwant %q", c.name, got, c.want)
		}
	}
}

func TestRejects(t *testing.T) {
	cases := map[string]error{
		"<html><?php echo 1; ?>":            ErrNotPlainCode,
		"<?php echo 1; ?>\n\n":              ErrNotPlainCode,
		"<?php echo 1; ?>x":                 ErrNotPlainCode,
		"<?php echo 1; ?>\n<?php":           ErrNotPlainCode,
		"<?php echo 1; ?> <?php echo 2;":    ErrNotPlainCode,
		"#!/usr/bin/env php\n<?php echo 1;": ErrNotPlainCode,
		"echo 1;":                           ErrNotPlainCode,
		"<?= 1;":                            ErrNotPlainCode,
		"<?php /* @generated by phaenon from A.phn */ echo 1;": ErrGenerated,
	}
	for in, want := range cases {
		_, err := File([]byte(in), Options{})
		if !errors.Is(err, want) {
			t.Errorf("%q: got %v, want %v", in, err, want)
		}
	}
}

func TestKeepLines(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{"psr-12 header", "<?php\n\ndeclare(strict_types=1);\n\nnamespace App;\n", "\n\n\n\nnamespace App;\n"},
		{"one-line header", "<?php declare(strict_types=1);\nnamespace App;\n", "\nnamespace App;\n"},
		{"code on the tag line", "<?php echo 1;\n", "echo 1;\n"},
		{"close tag", "<?php\necho 1;\n?>\n", "\necho 1;\n\n"},
	}
	for _, c := range cases {
		got, err := File([]byte(c.in), Options{KeepLines: true})
		if err != nil {
			t.Errorf("%s: %v", c.name, err)
			continue
		}
		if string(got) != c.want {
			t.Errorf("%s:\n got %q\nwant %q", c.name, got, c.want)
		}
	}
}
