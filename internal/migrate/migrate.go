// Package migrate rewrites plain PHP files as Phaenon files.
//
// Version 0 is mechanical: it removes the `<?php` tag, a leading
// `declare(strict_types=1);` (Phaenon is strict by default) and a trailing
// `?>`, and leaves everything else untouched. Template-style files — inline
// HTML, a `?>` in the middle, a shebang — stay PHP; a .phn is code from the
// first byte.
package migrate

import (
	"bytes"
	"errors"
	"fmt"
	"strings"

	"github.com/phaenonlang/phaenon/internal/ast"
	"github.com/phaenonlang/phaenon/internal/emit"
	"github.com/phaenonlang/phaenon/internal/lexer"
	"github.com/phaenonlang/phaenon/internal/parser"
)

// ErrNotPlainCode marks a PHP file that has no .phn equivalent: it has
// inline HTML, a close tag before the end, or does not start with <?php.
var ErrNotPlainCode = errors.New("file is not plain PHP code (inline HTML, ?> or no leading <?php tag)")

// ErrGenerated marks a .php file that was itself emitted from a .phn.
var ErrGenerated = errors.New("file is generated by phaenon; edit the .phn instead")

// Options control the migration.
type Options struct {
	// KeepLines leaves the removed tag and declare as blank text so every
	// line keeps its number (the conformance suite relies on it). Off, the
	// leading blank lines are dropped.
	KeepLines bool
}

// File converts PHP source to Phaenon source.
func File(src []byte, opts Options) ([]byte, error) {
	if emit.IsGenerated(src) {
		return nil, ErrGenerated
	}
	f, err := parser.Parse(src, lexer.ModePHP)
	if err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}
	if len(f.Stmts) == 0 {
		return nil, ErrNotPlainCode
	}
	open, ok := f.Stmts[0].(*ast.OpenTag)
	if !ok || open.S.Start != 0 {
		return nil, ErrNotPlainCode
	}
	stmts := f.Stmts[1:]
	// A close tag as the very last thing (it swallows one newline) is a
	// no-op idiom; anything else that leaves PHP mode makes a template.
	if n := len(stmts); n > 0 {
		if _, isClose := stmts[n-1].(*ast.CloseTag); isClose {
			stmts = stmts[:n-1]
		}
	}
	var bad bool
	for _, s := range stmts {
		ast.Inspect(s, func(n ast.Node) bool {
			switch n.(type) {
			case *ast.InlineHTML, *ast.CloseTag, *ast.OpenTag:
				bad = true
			}
			return !bad
		})
	}
	if bad {
		return nil, ErrNotPlainCode
	}

	// The open tag token ends with the whitespace character that follows
	// `<?php`; a line break there is kept so line numbers do not move.
	type edit struct {
		ast.Span
		text []byte
	}
	edits := []edit{{ast.Span{Start: 0, End: open.S.End - len(lineBreakSuffix(src[:open.S.End]))}, nil}}
	if len(stmts) > 0 {
		if d, ok := stmts[0].(*ast.Declare); ok && isStrictTypesOnly(d) {
			edits = append(edits, edit{d.S, nil})
		}
	}
	closeTag := len(stmts) < len(f.Stmts)-1 // a trailing close tag was dropped above
	if closeTag {
		if needsSemicolon(src, stmts) {
			// `echo 1 ?>` — the close tag doubled as the statement terminator.
			end := stmts[len(stmts)-1].Span().End
			edits = append(edits, edit{ast.Span{Start: end, End: end}, []byte(";")})
		}
		// The tag swallows the line break after it; keep that break so the
		// file still ends with one.
		tag := f.Stmts[len(f.Stmts)-1].Span()
		edits = append(edits, edit{tag, lineBreakSuffix(src[tag.Start:tag.End])})
	}
	var out []byte
	pos := 0
	for _, e := range edits {
		out = append(out, src[pos:e.Start]...)
		out = append(out, e.text...)
		pos = e.End
	}
	out = append(out, src[pos:]...)
	if !opts.KeepLines {
		out = bytes.TrimLeft(out, "\r\n")
		if closeTag {
			// `?>` on its own line usually sat after a blank line; one
			// trailing line break is enough once it is gone.
			trimmed := bytes.TrimRight(out, "\r\n")
			if len(trimmed) < len(out) {
				out = append(trimmed, '\n')
			}
		}
	}
	return out, nil
}

// needsSemicolon reports whether the last statement relied on the close
// tag as its terminator (`echo 1 ?>`, `$c = new class {} ?>`).
func needsSemicolon(src []byte, stmts []ast.Stmt) bool {
	if len(stmts) == 0 {
		return false
	}
	last := stmts[len(stmts)-1]
	text := bytes.TrimRight(src[last.Span().Start:last.Span().End], " \t\r\n")
	if bytes.HasSuffix(text, []byte(";")) {
		return false
	}
	switch last.(type) {
	case *ast.Label, *ast.HaltCompiler, *ast.Nop:
		return false
	case *ast.Block, *ast.If, *ast.While, *ast.For, *ast.Foreach, *ast.Switch, *ast.Try,
		*ast.ClassDecl, *ast.FunctionDecl, *ast.Namespace, *ast.Declare:
		// Self-terminating when they end with their own brace; the
		// alternative syntax (`endif`) and a brace-less branch do need `;`.
		return !bytes.HasSuffix(text, []byte("}"))
	}
	return true
}

// lineBreakSuffix returns the line break b ends with ("", "\n", "\r\n" or "\r").
func lineBreakSuffix(b []byte) []byte {
	switch {
	case bytes.HasSuffix(b, []byte("\r\n")):
		return b[len(b)-2:]
	case bytes.HasSuffix(b, []byte("\n")), bytes.HasSuffix(b, []byte("\r")):
		return b[len(b)-1:]
	}
	return nil
}

// isStrictTypesOnly reports whether d is exactly `declare(strict_types=1);`.
func isStrictTypesOnly(d *ast.Declare) bool {
	if d.Body != nil || d.Alt || len(d.Directives) != 1 {
		return false
	}
	dir := d.Directives[0]
	if !strings.EqualFold(dir.Name.Name, "strict_types") {
		return false
	}
	lit, ok := dir.Value.(*ast.IntLit)
	return ok && lit.Raw == "1"
}
